"""Export meeting analysis to Markdown and PDF — 100% local, no cloud services."""

import json
from io import BytesIO
from xml.sax.saxutils import escape


def parse_summary(summary):
    """Parse the JSON list fields of a MeetingSummary into Python lists."""
    if not summary:
        return [], [], []

    def _loads(text):
        try:
            data = json.loads(text) if text else []
            return data if isinstance(data, list) else []
        except Exception:
            return []

    return (
        _loads(summary.key_points),
        _loads(summary.action_items),
        _loads(summary.correlations),
    )


def _correlation_fields(c):
    """Normalize a correlation dict across the field-name variants used in the app."""
    ts = c.get('timestamp', '')
    if isinstance(ts, (int, float)):
        ts = format_timestamp(ts)
    return {
        'timestamp': str(ts or '00:00'),
        'speech': c.get('speech') or c.get('speech_text') or '',
        'screen': c.get('screen') or c.get('screen_text') or '',
        'insight': c.get('insight') or 'Correlated via timestamp proximity during presentation.',
    }


def format_timestamp(seconds):
    mins = int(seconds // 60)
    secs = int(seconds % 60)
    return f"{mins:02d}:{secs:02d}"


def format_duration(seconds):
    if not seconds:
        return 'Unknown'
    total = int(seconds)
    hours, rem = divmod(total, 3600)
    mins, secs = divmod(rem, 60)
    if hours:
        return f"{hours}h {mins}m {secs}s"
    return f"{mins}m {secs}s"


def _md_table_escape(text):
    return str(text).replace('|', '\\|').replace('\n', ' ').strip()


def generate_markdown(meeting, transcript_segments, screen_frames, summary):
    """Return a formatted Markdown report for the meeting."""
    key_points, action_items, correlations = parse_summary(summary)

    lines = [
        f"# {meeting.title}",
        "",
        f"**Date:** {meeting.created_at:%B %d, %Y • %I:%M %p}  |  "
        f"**Duration:** {format_duration(meeting.duration_seconds)}  |  "
        f"**Status:** {meeting.get_status_display()}",
        "",
        "> Generated by MeetMind — Local AI Meeting Intelligence. Processed 100% on-device.",
        "",
    ]

    if summary:
        lines += [
            "## Executive Summary",
            "",
            summary.overview or '_No overview generated._',
            "",
        ]
        if summary.full_summary and summary.full_summary != summary.overview:
            lines += [
                "## Comprehensive Briefing",
                "",
                summary.full_summary,
                "",
            ]

    lines += ["## Key Discussion Points", ""]
    if key_points:
        lines += [f"- {point}" for point in key_points]
    else:
        lines.append("_No key discussion points identified._")
    lines.append("")

    lines += ["## Action Items", ""]
    if action_items:
        lines += [f"- [ ] {item}" for item in action_items]
    else:
        lines.append("_No action items identified._")
    lines.append("")

    lines += [
        "## Speech ↔ Screen Correlations",
        "",
        "| Timestamp | What Was Said | Screen Content | AI Insight |",
        "|-----------|---------------|----------------|------------|",
    ]
    if correlations:
        for raw in correlations:
            c = _correlation_fields(raw)
            lines.append(
                f"| {_md_table_escape(c['timestamp'])} | {_md_table_escape(c['speech'])} "
                f"| {_md_table_escape(c['screen'])} | {_md_table_escape(c['insight'])} |"
            )
    else:
        lines.append("| — | _No correlations generated._ | | |")
    lines.append("")

    lines += [
        "## Full Transcript",
        "",
        "| Time | Speaker | Text |",
        "|------|---------|------|",
    ]
    for seg in transcript_segments:
        speaker = seg.speaker or '—'
        lines.append(
            f"| {seg.formatted_start} | {_md_table_escape(speaker)} | {_md_table_escape(seg.text)} |"
        )
    lines.append("")

    if screen_frames:
        lines += [
            "## Screen Content (OCR)",
            "",
            "| Timestamp | Extracted Text |",
            "|-----------|----------------|",
        ]
        for frame in screen_frames:
            lines.append(
                f"| {frame.formatted_timestamp} | {_md_table_escape(frame.ocr_text or '—')} |"
            )
        lines.append("")

    return "\n".join(lines)


def generate_pdf(meeting, transcript_segments, screen_frames, summary):
    """Return a BytesIO buffer containing a styled PDF report."""
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.lib import colors
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.platypus import (
        SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable,
    )

    key_points, action_items, correlations = parse_summary(summary)

    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=20 * mm,
        bottomMargin=18 * mm,
        title=f"MeetMind — {meeting.title}",
        author="MeetMind (Local AI)",
    )

    styles = getSampleStyleSheet()
    accent = colors.HexColor('#4f46e5')   # indigo
    emerald = colors.HexColor('#059669')
    zinc_500 = colors.HexColor('#71717a')
    zinc_200 = colors.HexColor('#e4e4e7')
    zinc_100 = colors.HexColor('#f4f4f5')

    s_title = ParagraphStyle('MMTitle', parent=styles['Title'], fontSize=20, leading=24, spaceAfter=4)
    s_meta = ParagraphStyle('MMMeta', parent=styles['Normal'], fontSize=8.5, textColor=zinc_500, spaceAfter=2)
    s_h2 = ParagraphStyle('MMH2', parent=styles['Heading2'], fontSize=13, leading=16,
                          textColor=accent, spaceBefore=14, spaceAfter=6)
    s_body = ParagraphStyle('MMBody', parent=styles['Normal'], fontSize=9.5, leading=14)
    s_bullet = ParagraphStyle('MMBullet', parent=s_body, leftIndent=10, spaceAfter=3)
    s_cell = ParagraphStyle('MMCell', parent=s_body, fontSize=8, leading=11)
    s_cell_head = ParagraphStyle('MMCellHead', parent=s_cell, fontName='Helvetica-Bold',
                                 textColor=colors.white)
    s_watermark = ParagraphStyle('MMWatermark', parent=s_meta, alignment=1, fontSize=8)

    def p(text, style=s_body):
        return Paragraph(escape(str(text or '')).replace('\n', '<br/>'), style)

    story = []

    # Header
    story.append(p(meeting.title, s_title))
    story.append(p(
        f"Date: {meeting.created_at:%B %d, %Y • %I:%M %p}  |  "
        f"Duration: {format_duration(meeting.duration_seconds)}  |  "
        f"Status: {meeting.get_status_display()}",
        s_meta,
    ))
    story.append(HRFlowable(width='100%', thickness=1, color=accent, spaceBefore=4, spaceAfter=2))

    if summary:
        story.append(p('Executive Summary', s_h2))
        story.append(p(summary.overview or 'No overview generated.'))
        if summary.full_summary and summary.full_summary != summary.overview:
            story.append(p('Comprehensive Briefing', s_h2))
            story.append(p(summary.full_summary, ParagraphStyle('MMSmall', parent=s_body,
                                                                textColor=zinc_500, fontSize=8.5)))

    story.append(p('Key Discussion Points', s_h2))
    if key_points:
        for point in key_points:
            story.append(p(f'• {point}', s_bullet))
    else:
        story.append(p('No key discussion points identified.', s_meta))

    story.append(p('Action Items', s_h2))
    if action_items:
        for item in action_items:
            story.append(p(f'☐ {item}', s_bullet))
    else:
        story.append(p('No action items identified.', s_meta))

    def styled_table(header, rows, col_widths):
        data = [[p(h, s_cell_head) for h in header]] + rows
        table = Table(data, colWidths=col_widths, repeatRows=1)
        table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), accent),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, zinc_100]),
            ('GRID', (0, 0), (-1, -1), 0.4, zinc_200),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('LEFTPADDING', (0, 0), (-1, -1), 5),
            ('RIGHTPADDING', (0, 0), (-1, -1), 5),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        return table

    page_width = A4[0] - 36 * mm

    story.append(p('Speech ↔ Screen Correlations', s_h2))
    if correlations:
        rows = []
        for raw in correlations:
            c = _correlation_fields(raw)
            rows.append([
                p(c['timestamp'], s_cell),
                p(c['speech'], s_cell),
                p(c['screen'], s_cell),
                p(c['insight'], s_cell),
            ])
        story.append(styled_table(
            ['Time', 'What Was Said', 'Screen Content', 'AI Insight'],
            rows,
            [page_width * 0.09, page_width * 0.32, page_width * 0.32, page_width * 0.27],
        ))
    else:
        story.append(p('No correlations generated.', s_meta))

    story.append(p('Full Transcript', s_h2))
    if transcript_segments:
        rows = [
            [p(seg.formatted_start, s_cell), p(seg.speaker or '—', s_cell), p(seg.text, s_cell)]
            for seg in transcript_segments
        ]
        story.append(styled_table(
            ['Time', 'Speaker', 'Text'],
            rows,
            [page_width * 0.09, page_width * 0.14, page_width * 0.77],
        ))
    else:
        story.append(p('No transcript available.', s_meta))

    if screen_frames:
        story.append(p('Screen Content (OCR)', s_h2))
        rows = [
            [p(frame.formatted_timestamp, s_cell), p(frame.ocr_text or '—', s_cell)]
            for frame in screen_frames
        ]
        story.append(styled_table(
            ['Timestamp', 'Extracted Text'],
            rows,
            [page_width * 0.14, page_width * 0.86],
        ))

    story.append(Spacer(1, 10))
    story.append(HRFlowable(width='100%', thickness=0.5, color=zinc_200, spaceBefore=4, spaceAfter=4))
    story.append(p(
        'Generated by MeetMind — Local AI Meeting Intelligence. '
        'All processing performed on-device. No data left this machine.',
        s_watermark,
    ))

    def _footer(canvas, doc_obj):
        canvas.saveState()
        canvas.setFont('Helvetica', 7.5)
        canvas.setFillColor(zinc_500)
        canvas.drawString(18 * mm, 10 * mm, 'MeetMind — Local AI Meeting Intelligence')
        canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f'Page {doc_obj.page}')
        canvas.restoreState()

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    buffer.seek(0)
    return buffer
